"""
Gromov-Wasserstein Optimal Transport & Transductive Clique Calibration for 'Name That LLM'.

Mathematical Architecture & Scientific Treatises
------------------------------------------------
1. ENTROPIC & UNBALANCED GROMOV-WASSERSTEIN MATCHING (Peyre et al. 2016, 2019; Sejourne et al. 2021):
   Given an inferred prompt clique of size n (passages answering the exact same prompt),
   no two passages can be generated by the same LLM (the model assignment is injective).
   The intra-clique passage cosine distance matrix D_X in R^{n x n} and candidate model
   prototype geometry D_Y in R^{K x K} (K = 18) are aligned by finding a coupling matrix
   T in R_+^{n x K} that minimizes the Fused Gromov-Wasserstein (FGW) objective:

     min_{T >= 0} (1 - alpha_gw) <M, T> + alpha_gw E_GW(T; D_X, D_Y) + eps * KL(T || p (x) q)
                  + tau_col * KL(T^T 1 || q)

   subject to strict row-stochasticity T 1 = p = 1/n.
   For quadratic loss L(a, b) = (a - b)^2, the tensor contraction gradient evaluates in O(n^2 K + n K^2):
     G(T) = (D_X^{.2} (T 1_K)) 1_K^T + 1_n (D_Y^{.2} (T^T 1_n))^T - 2 D_X T D_Y^T
   Picard / Frank-Wolfe outer updates alternate between evaluating G(T) and solving the
   inner log-domain generalized Sinkhorn proximal step contracting at rate kappa = tau_col / (tau_col + eps).

2. TRANSDUCTIVE CLIQUE CALIBRATION WITH CONTINUOUS REGIME HOMOTOPY:
   Small cliques provide different degrees of combinatorial constraint than full cliques.
   `TransductiveCliqueCalibrator` smoothly interpolates along a C^1 continuous homotopy:
     - Singleton (n = 1): Unconstrained temperature-scaled softmax. No mutual exclusion distractor.
     - Small cliques (2 <= n < 6): Soft cavity occupation repulsion:
         Delta L_{ij} = - lambda_repel(n) * log(1 + sum_{k != i} P_{kj})
       preventing collision on popular classes without forcing premature column balance.
     - Moderate to full cliques (6 <= n <= 18): Unbalanced Sinkhorn / Gromov-Wasserstein matching
       with column relaxation tau_col(n) smoothly hardening as n -> 18.
     - Oversized cliques (n > 18): Softened column relaxation preventing degenerate assignment.

3. CONFIDENCE-WEIGHTED HODGERANK (Jiang et al. 2011; Lim 2020):
   Given pairwise sibling preferences or log-odds flows Y_{ij} in R, projects onto the
   curl-free gradient of a global potential s in R^K via weighted combinatorial graph Helmholtz-Hodge:
     min_s 1/2 sum_{i < j} W_{ij} (s_j - s_i - Y_{ij})^2  ==>  L_W s = div_W(Y)
   where edge weights incorporate classifier margin confidence:
     W_{ij} = w_{ij}^{base} * (eps_floor + |Y_{ij}|^beta).
   The projected gradient flow Y_hat_{ij} = s_j - s_i is mathematically guaranteed to have
   identically ZERO curl on every cycle:
     curl(Y_hat)_{ijk} = Y_hat_{ij} + Y_hat_{jk} + Y_hat_{ki} == 0
   completely eliminating Condorcet voting paradoxes and circular preference loops.
"""

